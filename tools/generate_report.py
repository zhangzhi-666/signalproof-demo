def case_examples(fixtures):
    blocks=[]
    for key in ('F02-ERR','F14-ERR','Z09-ERR'):
        case=next(x for x in fixtures if x['id']==key)
        result=dispatch({'action':'verify','steps':case['steps'],'context':case.get('context',{})})
        body=''.join(f'<div class="equation"><span>E{i+1}</span><div>{formula(tex,case["steps"][i])}'+('<small>ROC</small>'+formula(result['rocLatex'][i],'') if result['rocLatex'][i] else '')+'</div></div>' for i,tex in enumerate(result['latex']))
        error=next((x for x in result['steps'] if x['line']==result['firstError']),None)
        detail=f'<p>{esc(result["summary"])}</p>'
        if error:
            label = '规则：'+ ' / '.join(error['ruleIds'])+'；' if error['ruleIds'] else '依据：'
            detail+=f'<p>{esc(label)}{esc(error["explanation"])}</p>'
            if error.get('expectedLatex'): detail+='<p>候选修正：</p>'+formula(error['expectedLatex'],error['expected'])
            if error.get('expectedRocLatex'): detail+='<p>ROC：</p>'+formula(error['expectedRocLatex'],'')
        blocks.append(f'<article class="case"><h3>{esc(case["id"])} · {esc(case["title"])}</h3>{body}{detail}</article>')
    return ''.join(blocks)


