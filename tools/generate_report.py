def esc(value):
    return html.escape(str(value))


def table(headers, rows):
    return '<div class="table-wrap"><table><thead><tr>' + ''.join(f'<th>{esc(h)}</th>' for h in headers) + '</tr></thead><tbody>' + ''.join('<tr>' + ''.join(f'<td>{esc(c)}</td>' for c in row) + '</tr>' for row in rows) + '</tbody></table></div>'


def metric(value):
    return f"{value['rate'] * 100:.2f}% ({value['correct']}/{value['total']})" if value['total'] else '不适用'


def timing(value):
    return f'{value:.3f}' if value is not None else '无已完成测量'


def validate_measurement(report):
    """Do not mix old measurements with examples generated by changed source."""
    if not report['source'].get('unchangedDuringRun'):
        raise ValueError('Core changed during measurement; rerun benchmark first.')
    expected = dict(report['source']['files'])
    expected.update({item['path']: item['sha256'] for item in report['datasets'].values()})
    expected['data/step-oracles.json'] = report['datasets']['baseline']['oracleSha256']
    expected['tools/benchmark.py'] = report['source']['benchmarkSha256']
    for path, digest in expected.items():
        if hashlib.sha256((ROOT/path).read_bytes()).hexdigest() != digest:
            raise ValueError(f'Measurement is stale for {path}; rerun benchmark before generating the report.')


def formula(latex, fallback):
    return f'<div class="math" data-tex="{esc(latex)}">{esc(fallback)}</div>'


